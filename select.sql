USE library_management_system;

-- ---------- basic queries ----------

-- Q1 all books
SELECT * FROM BOOKS;

-- Q2 all students
SELECT * FROM STUDENT;

-- Q3 books published after 2010
SELECT BOOKID, TITLE, PUBLICATIONYEAR FROM BOOKS
WHERE PUBLICATIONYEAR > 2010
ORDER BY PUBLICATIONYEAR DESC;

-- Q4 books in the Central Library (WHERE)
SELECT BOOKID, TITLE, CATEGORY FROM BOOKS
WHERE LIBRARYID = 1;

-- Q5 database books after 2010 (AND)
SELECT TITLE, CATEGORY, PUBLICATIONYEAR FROM BOOKS
WHERE CATEGORY = 'Database' AND PUBLICATIONYEAR > 2010;

-- Q6 programming or algorithm books (OR)
SELECT TITLE, CATEGORY FROM BOOKS
WHERE CATEGORY = 'Programming' OR CATEGORY = 'Algorithms';

-- Q7 books published between 2005 and 2015 (BETWEEN)
SELECT TITLE, PUBLICATIONYEAR FROM BOOKS
WHERE PUBLICATIONYEAR BETWEEN 2005 AND 2015
ORDER BY PUBLICATIONYEAR;

-- Q8 students from CSE, IT, AIDS, AIML (IN)
SELECT STUDENTNAME, BRANCH, SEMESTER FROM STUDENT
WHERE BRANCH IN ('CSE', 'IT', 'AIDS', 'AIML');

-- Q9 search books by title (LIKE)
SELECT BOOKID, TITLE FROM BOOKS
WHERE TITLE LIKE '%Database%';

-- Q10 students whose name starts with A
SELECT STUDENTNAME, STUDENTEMAIL FROM STUDENT
WHERE STUDENTNAME LIKE 'A%';

-- Q11 books still not returned (IS NULL)
SELECT BORROWID, STUDENTID, BOOKID, BORROWDATE, DUE_DATE FROM BORROW
WHERE RETURNDATE IS NULL;

-- Q12 books with no ISBN
SELECT BOOKID, TITLE FROM BOOKS WHERE ISBN IS NULL;

-- Q13 returned loans (IS NOT NULL)
SELECT BORROWID, BORROWDATE, RETURNDATE FROM BORROW
WHERE RETURNDATE IS NOT NULL
ORDER BY RETURNDATE DESC;

-- Q14 students sorted by semester then name (ORDER BY)
SELECT STUDENTNAME, BRANCH, SEMESTER FROM STUDENT
ORDER BY SEMESTER DESC, STUDENTNAME;

-- Q15 all categories without repeats (DISTINCT)
SELECT DISTINCT CATEGORY FROM BOOKS ORDER BY CATEGORY;

-- Q16 5 newest books (LIMIT)
SELECT TITLE, PUBLICATIONYEAR FROM BOOKS
ORDER BY PUBLICATIONYEAR DESC
LIMIT 5;


-- ---------- aggregate functions ----------

-- Q17 total number of book copies
SELECT COUNT(*) AS total_books FROM BOOKS;

-- Q18 number of different titles
SELECT COUNT(DISTINCT TITLE) AS unique_titles FROM BOOKS;

-- Q19 number of overdue loans
SELECT COUNT(*) AS overdue FROM BORROW
WHERE RETURNDATE IS NULL AND DUE_DATE < CURDATE();

-- Q20 total days books were kept (returned loans)
SELECT SUM(DATEDIFF(RETURNDATE, BORROWDATE)) AS total_days_kept
FROM BORROW WHERE RETURNDATE IS NOT NULL;

-- Q21 average days a book is kept
SELECT ROUND(AVG(DATEDIFF(RETURNDATE, BORROWDATE)), 1) AS avg_days
FROM BORROW WHERE RETURNDATE IS NOT NULL;

-- Q22 oldest and newest publication year
SELECT MIN(PUBLICATIONYEAR) AS oldest, MAX(PUBLICATIONYEAR) AS newest FROM BOOKS;

-- Q23 first and latest borrow date
SELECT MIN(BORROWDATE) AS first_borrow, MAX(BORROWDATE) AS latest_borrow FROM BORROW;


-- ---------- group by / having ----------

-- Q24 books in each library
SELECT L.NAME, COUNT(B.BOOKID) AS total_books
FROM LIBRARY L
JOIN BOOKS B ON L.LIBRARYID = B.LIBRARYID
GROUP BY L.LIBRARYID, L.NAME;

-- Q25 books from each publisher
SELECT P.NAME, COUNT(B.BOOKID) AS total_books
FROM PUBLISHER P
JOIN BOOKS B ON P.PUBLISHERID = B.PUBLISHERID
GROUP BY P.PUBLISHERID, P.NAME
ORDER BY total_books DESC;

-- Q26 students in each branch
SELECT BRANCH, COUNT(*) AS students FROM STUDENT
GROUP BY BRANCH;

-- Q27 books per category
SELECT CATEGORY, COUNT(*) AS books FROM BOOKS
GROUP BY CATEGORY
ORDER BY books DESC;

-- Q28 students who borrowed more than 1 book (HAVING)
SELECT S.STUDENTID, S.STUDENTNAME, COUNT(BR.BORROWID) AS times_borrowed
FROM STUDENT S
JOIN BORROW BR ON S.STUDENTID = BR.STUDENTID
GROUP BY S.STUDENTID, S.STUDENTNAME
HAVING COUNT(BR.BORROWID) > 1;

-- Q29 libraries with more than 10 books
SELECT L.NAME, COUNT(B.BOOKID) AS total_books
FROM LIBRARY L
JOIN BOOKS B ON L.LIBRARYID = B.LIBRARYID
GROUP BY L.LIBRARYID, L.NAME
HAVING COUNT(B.BOOKID) > 10;


-- ---------- subqueries ----------

-- Q30 books newer than the average year (scalar subquery)
SELECT TITLE, PUBLICATIONYEAR FROM BOOKS
WHERE PUBLICATIONYEAR > (SELECT AVG(PUBLICATIONYEAR) FROM BOOKS);

-- Q31 students who borrowed at least once (IN, multiple rows)
SELECT STUDENTID, STUDENTNAME FROM STUDENT
WHERE STUDENTID IN (SELECT STUDENTID FROM BORROW);

-- Q32 students who never borrowed (NOT IN)
SELECT STUDENTID, STUDENTNAME FROM STUDENT
WHERE STUDENTID NOT IN (SELECT STUDENTID FROM BORROW);

-- Q33 students who have a book right now (EXISTS, correlated)
SELECT STUDENTID, STUDENTNAME FROM STUDENT S
WHERE EXISTS (
    SELECT 1 FROM BORROW B
    WHERE B.STUDENTID = S.STUDENTID AND B.RETURNDATE IS NULL
);

-- Q34 books never borrowed (NOT EXISTS)
SELECT BOOKID, TITLE FROM BOOKS B
WHERE NOT EXISTS (SELECT 1 FROM BORROW BR WHERE BR.BOOKID = B.BOOKID);

-- Q35 students whose borrowing count is above the average across all students,
-- including students with zero borrowings
SELECT S.STUDENTNAME,
       (SELECT COUNT(*) FROM BORROW BR WHERE BR.STUDENTID = S.STUDENTID) AS times_borrowed
FROM STUDENT S
WHERE (SELECT COUNT(*) FROM BORROW BR WHERE BR.STUDENTID = S.STUDENTID) >
      ((SELECT COUNT(*) FROM BORROW) / (SELECT COUNT(*) FROM STUDENT));

-- Q36 books newer than ALL Addison-Wesley books (ALL)
SELECT TITLE, PUBLICATIONYEAR FROM BOOKS
WHERE PUBLICATIONYEAR > ALL (SELECT PUBLICATIONYEAR FROM BOOKS WHERE PUBLISHERID = 3);

-- Q37 books newer than at least one Wiley book (ANY)
SELECT TITLE, PUBLICATIONYEAR FROM BOOKS
WHERE PUBLICATIONYEAR > ANY (SELECT PUBLICATIONYEAR FROM BOOKS WHERE PUBLISHERID = 4);

-- Q38 books with more than one author (subquery in FROM)
SELECT B.TITLE, x.author_count
FROM BOOKS B
JOIN (
    SELECT BOOKID, COUNT(*) AS author_count
    FROM WRITTEN_BY
    GROUP BY BOOKID
    HAVING COUNT(*) > 1
) x ON B.BOOKID = x.BOOKID;

-- Q39 overdue books with student names
SELECT BR.BORROWID, S.STUDENTNAME, B.TITLE, BR.DUE_DATE,
       DATEDIFF(CURDATE(), BR.DUE_DATE) AS days_late
FROM BORROW BR
JOIN STUDENT S ON BR.STUDENTID = S.STUDENTID
JOIN BOOKS B ON BR.BOOKID = B.BOOKID
WHERE BR.RETURNDATE IS NULL AND BR.DUE_DATE < CURDATE()
ORDER BY days_late DESC;
