USE library_management_system;

SELECT VERSION() AS MySQLServerVersion;

-- ---------- inner join ----------

-- J1 books with publisher name
SELECT B.BOOKID, B.TITLE, P.NAME AS publisher
FROM BOOKS B
INNER JOIN PUBLISHER P ON B.PUBLISHERID = P.PUBLISHERID
ORDER BY P.NAME, B.TITLE;

-- J2 borrowed books with student name
SELECT BR.BORROWID, S.STUDENTNAME, B.TITLE, BR.BORROWDATE, BR.RETURNDATE
FROM BORROW BR
INNER JOIN STUDENT S ON BR.STUDENTID = S.STUDENTID
INNER JOIN BOOKS B ON BR.BOOKID = B.BOOKID
ORDER BY BR.BORROWDATE DESC;

-- J3 books with authors (goes through WRITTEN_BY)
SELECT B.BOOKID, B.TITLE, A.NAME AS author
FROM BOOKS B
INNER JOIN WRITTEN_BY WB ON B.BOOKID = WB.BOOKID
INNER JOIN AUTHOR A ON WB.AUTHORID = A.AUTHORID
ORDER BY B.TITLE, A.NAME;


-- ---------- left join ----------

-- J4 all students, even those who never borrowed
SELECT S.STUDENTID, S.STUDENTNAME, COUNT(BR.BORROWID) AS times_borrowed
FROM STUDENT S
LEFT JOIN BORROW BR ON S.STUDENTID = BR.STUDENTID
GROUP BY S.STUDENTID, S.STUDENTNAME
ORDER BY times_borrowed DESC;

-- J5 only the students who never borrowed (left join + IS NULL)
SELECT S.STUDENTID, S.STUDENTNAME, S.BRANCH
FROM STUDENT S
LEFT JOIN BORROW BR ON S.STUDENTID = BR.STUDENTID
WHERE BR.BORROWID IS NULL;

-- J6 all books with how many times each was borrowed
SELECT B.BOOKID, B.TITLE, COUNT(BR.BORROWID) AS times_borrowed
FROM BOOKS B
LEFT JOIN BORROW BR ON B.BOOKID = BR.BOOKID
GROUP BY B.BOOKID, B.TITLE
ORDER BY times_borrowed DESC;


-- ---------- right join ----------

-- J7 all publishers, even if no book (right table = PUBLISHER)
SELECT P.NAME AS publisher, COUNT(B.BOOKID) AS books
FROM BOOKS B
RIGHT JOIN PUBLISHER P ON B.PUBLISHERID = P.PUBLISHERID
GROUP BY P.PUBLISHERID, P.NAME;

-- J8 all authors with number of books written
SELECT A.NAME AS author, COUNT(WB.BOOKID) AS books
FROM WRITTEN_BY WB
RIGHT JOIN AUTHOR A ON WB.AUTHORID = A.AUTHORID
GROUP BY A.AUTHORID, A.NAME
ORDER BY books DESC;


-- ---------- self join ----------

-- J9 pairs of different students in same branch and semester
SELECT S1.STUDENTNAME AS student1, S2.STUDENTNAME AS student2, S1.BRANCH, S1.SEMESTER
FROM STUDENT S1
INNER JOIN STUDENT S2
    ON S1.BRANCH = S2.BRANCH
   AND S1.SEMESTER = S2.SEMESTER
   AND S1.STUDENTID < S2.STUDENTID   -- so (A,B) and (B,A) don't both show
ORDER BY S1.BRANCH, S1.SEMESTER;

-- J10 different copies of the same title (self join on BOOKS)
SELECT B1.TITLE, B1.BOOKID AS copy1, B2.BOOKID AS copy2
FROM BOOKS B1
INNER JOIN BOOKS B2
    ON B1.TITLE = B2.TITLE AND B1.BOOKID < B2.BOOKID
ORDER BY B1.TITLE;


-- ---------- multiple joins ----------

-- J11 book title, author, publisher, library
SELECT B.TITLE, A.NAME AS author, P.NAME AS publisher, L.NAME AS library
FROM BOOKS B
INNER JOIN WRITTEN_BY WB ON B.BOOKID = WB.BOOKID
INNER JOIN AUTHOR A ON WB.AUTHORID = A.AUTHORID
INNER JOIN PUBLISHER P ON B.PUBLISHERID = P.PUBLISHERID
INNER JOIN LIBRARY L ON B.LIBRARYID = L.LIBRARYID
ORDER BY B.TITLE, A.NAME;

-- J12 borrowing history with book title, student name, library
SELECT BR.BORROWID, S.STUDENTNAME, B.TITLE, L.NAME AS library,
       BR.BORROWDATE, BR.DUE_DATE, BR.RETURNDATE
FROM BORROW BR
INNER JOIN STUDENT S ON BR.STUDENTID = S.STUDENTID
INNER JOIN BOOKS B ON BR.BOOKID = B.BOOKID
INNER JOIN LIBRARY L ON B.LIBRARYID = L.LIBRARYID
ORDER BY BR.BORROWDATE DESC;

-- J13 each book with all its authors in one row
SELECT B.BOOKID, B.TITLE, GROUP_CONCAT(A.NAME SEPARATOR ', ') AS authors
FROM BOOKS B
INNER JOIN WRITTEN_BY WB ON B.BOOKID = WB.BOOKID
INNER JOIN AUTHOR A ON WB.AUTHORID = A.AUTHORID
GROUP BY B.BOOKID, B.TITLE
HAVING COUNT(A.AUTHORID) > 1;


SELECT S.STUDENTID, S.STUDENTNAME, BR.BORROWID, BR.BOOKID
FROM STUDENT S
LEFT JOIN BORROW BR ON S.STUDENTID = BR.STUDENTID
UNION
SELECT S.STUDENTID, S.STUDENTNAME, BR.BORROWID, BR.BOOKID
FROM STUDENT S
RIGHT JOIN BORROW BR ON S.STUDENTID = BR.STUDENTID;

-- note: because of the foreign key every borrow has a student,
-- so here the result is the same as the left join.


-- ---------- set operations ----------

-- S1 UNION: students who borrowed Database books or AI/ML books (no repeats)
SELECT S.STUDENTID, S.STUDENTNAME
FROM STUDENT S
JOIN BORROW BR ON S.STUDENTID = BR.STUDENTID
JOIN BOOKS B ON BR.BOOKID = B.BOOKID
WHERE B.CATEGORY = 'Database'
UNION
SELECT S.STUDENTID, S.STUDENTNAME
FROM STUDENT S
JOIN BORROW BR ON S.STUDENTID = BR.STUDENTID
JOIN BOOKS B ON BR.BOOKID = B.BOOKID
WHERE B.CATEGORY = 'AI/ML';

-- S2 UNION ALL: same thing but keeps duplicates
SELECT BR.STUDENTID FROM BORROW BR JOIN BOOKS B ON BR.BOOKID = B.BOOKID
WHERE B.CATEGORY = 'Database'
UNION ALL
SELECT BR.STUDENTID FROM BORROW BR JOIN BOOKS B ON BR.BOOKID = B.BOOKID
WHERE B.CATEGORY = 'AI/ML';


SELECT S.STUDENTID, S.STUDENTNAME
FROM STUDENT S
WHERE EXISTS (SELECT 1 FROM BORROW BR JOIN BOOKS B ON BR.BOOKID = B.BOOKID
              WHERE BR.STUDENTID = S.STUDENTID AND B.CATEGORY = 'Database')
  AND EXISTS (SELECT 1 FROM BORROW BR JOIN BOOKS B ON BR.BOOKID = B.BOOKID
              WHERE BR.STUDENTID = S.STUDENTID AND B.CATEGORY = 'Networks');

SELECT S.STUDENTID, S.STUDENTNAME
FROM STUDENT S
WHERE EXISTS (SELECT 1 FROM BORROW BR JOIN BOOKS B ON BR.BOOKID = B.BOOKID
              WHERE BR.STUDENTID = S.STUDENTID AND B.CATEGORY = 'Database')
  AND NOT EXISTS (SELECT 1 FROM BORROW BR JOIN BOOKS B ON BR.BOOKID = B.BOOKID
                  WHERE BR.STUDENTID = S.STUDENTID AND B.CATEGORY = 'Programming');
