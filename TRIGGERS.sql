USE library_management_system;

DROP TRIGGER IF EXISTS TRG_BEFORE_INSERT_BORROW;
DROP TRIGGER IF EXISTS TRG_BEFORE_UPDATE_BORROW;
DROP TRIGGER IF EXISTS TRG_BEFORE_INSERT_BOOKS;
DROP TRIGGER IF EXISTS TRG_BEFORE_INSERT_STUDENT;

DELIMITER //

CREATE TRIGGER TRG_BEFORE_INSERT_BORROW
BEFORE INSERT ON BORROW
FOR EACH ROW
BEGIN
    IF NEW.BORROWDATE IS NULL OR NEW.BORROWDATE > CURDATE() THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'BORROWDATE must be today or an earlier date.';
    END IF;

    IF NEW.DUE_DATE IS NULL OR NEW.DUE_DATE <= NEW.BORROWDATE THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'DUE_DATE must be later than BORROWDATE.';
    END IF;
END //

CREATE TRIGGER TRG_BEFORE_UPDATE_BORROW
BEFORE UPDATE ON BORROW
FOR EACH ROW
BEGIN
    IF NEW.BORROWDATE <> OLD.BORROWDATE THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'BORROWDATE cannot be changed after a loan is recorded.';
    END IF;

    IF NEW.DUE_DATE <> OLD.DUE_DATE THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'DUE_DATE cannot be changed after a loan is recorded.';
    END IF;

    IF NEW.RETURNDATE IS NOT NULL AND NEW.RETURNDATE < NEW.BORROWDATE THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'RETURNDATE cannot be before BORROWDATE.';
    END IF;

    IF OLD.RETURNDATE IS NOT NULL AND NEW.RETURNDATE IS NULL THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'A returned loan cannot be reopened; create a new loan instead.';
    END IF;

    IF OLD.RETURNDATE IS NOT NULL
       AND NEW.RETURNDATE IS NOT NULL
       AND NEW.RETURNDATE <> OLD.RETURNDATE THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'A completed loan return date cannot be changed.';
    END IF;
END //

CREATE TRIGGER TRG_BEFORE_INSERT_BOOKS
BEFORE INSERT ON BOOKS
FOR EACH ROW
BEGIN
    IF NEW.PUBLICATIONYEAR < 1800
       OR NEW.PUBLICATIONYEAR > YEAR(CURDATE()) + 1 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'PUBLICATIONYEAR must be between 1800 and next year.';
    END IF;

    IF TRIM(NEW.TITLE) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'BOOKS.TITLE cannot be blank.';
    END IF;
END //

CREATE TRIGGER TRG_BEFORE_INSERT_STUDENT
BEFORE INSERT ON STUDENT
FOR EACH ROW
BEGIN
    IF TRIM(NEW.STUDENTNAME) = '' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'STUDENTNAME cannot be blank.';
    END IF;

    IF LENGTH(TRIM(NEW.USERID)) < 5 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'USERID must be at least five characters long.';
    END IF;
END //

DELIMITER ;

SHOW TRIGGERS FROM library_management_system;
