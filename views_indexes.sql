-- ---------- indexes ----------
-- PK, UNIQUE and FK columns already get an index automatically,
-- so these are only for other columns we search a lot

-- before creating the index, check the plan for a title search
EXPLAIN SELECT BOOKID, TITLE FROM BOOKS WHERE TITLE = 'Introduction to Algorithms';

-- title is searched a lot
CREATE INDEX IDX_BOOKS_TITLE ON BOOKS(TITLE);

-- Compare this plan with the result above. The optimizer may still choose a
-- table scan, especially for a small table; index use is not guaranteed.
EXPLAIN SELECT BOOKID, TITLE FROM BOOKS WHERE TITLE = 'Introduction to Algorithms';

-- for "books after year x" queries
CREATE INDEX IDX_BOOKS_YEAR ON BOOKS(PUBLICATIONYEAR);

-- branch is used in WHERE and GROUP BY
CREATE INDEX IDX_STUDENT_BRANCH ON STUDENT(BRANCH);

-- date range searches on borrow
CREATE INDEX IDX_BORROW_BORROWDATE ON BORROW(BORROWDATE);

-- "is this book currently borrowed" checks (used by the procedure and trigger)
CREATE INDEX IDX_BORROW_BOOK_RETURN ON BORROW(BOOKID, RETURNDATE);

SHOW INDEX FROM BOOKS;
SHOW INDEX FROM BORROW;
SHOW INDEX FROM STUDENT;

