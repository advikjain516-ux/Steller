USE library_management_system;

-- ---------- views ----------
-- a view is a saved SELECT, we can query it like a table

-- 1. AVAILABLE_BOOKS: copies that are not borrowed right now
-- (availability is worked out from BORROW, not stored in a column)
CREATE OR REPLACE VIEW AVAILABLE_BOOKS AS
SELECT B.BOOKID, B.TITLE, B.ISBN, B.CATEGORY, B.PUBLICATIONYEAR,
       P.NAME AS PUBLISHER, L.NAME AS LIBRARY
FROM BOOKS B
JOIN PUBLISHER P ON B.PUBLISHERID = P.PUBLISHERID
JOIN LIBRARY L ON B.LIBRARYID = L.LIBRARYID
WHERE NOT EXISTS (
    SELECT 1 FROM BORROW BR
    WHERE BR.BOOKID = B.BOOKID AND BR.RETURNDATE IS NULL
);

SELECT * FROM AVAILABLE_BOOKS ORDER BY TITLE;

-- 2. CURRENT_BORROWINGS: loans that are not returned yet
CREATE OR REPLACE VIEW CURRENT_BORROWINGS AS
SELECT BR.BORROWID, S.STUDENTID, S.STUDENTNAME, B.BOOKID, B.TITLE,
       L.NAME AS LIBRARY, BR.BORROWDATE, BR.DUE_DATE
FROM BORROW BR
JOIN STUDENT S ON BR.STUDENTID = S.STUDENTID
JOIN BOOKS B ON BR.BOOKID = B.BOOKID
JOIN LIBRARY L ON B.LIBRARYID = L.LIBRARYID
WHERE BR.RETURNDATE IS NULL;

SELECT * FROM CURRENT_BORROWINGS;

-- 3. STUDENT_BORROWING_HISTORY: every loan (returned or not) with status
CREATE OR REPLACE VIEW STUDENT_BORROWING_HISTORY AS
SELECT S.STUDENTID, S.STUDENTNAME, B.TITLE, BR.BORROWID,
       BR.BORROWDATE, BR.DUE_DATE, BR.RETURNDATE,
       CASE
           WHEN BR.RETURNDATE IS NOT NULL THEN 'Returned'
           WHEN BR.DUE_DATE < CURDATE() THEN 'Overdue'
           ELSE 'Active'
       END AS STATUS
FROM BORROW BR
JOIN STUDENT S ON BR.STUDENTID = S.STUDENTID
JOIN BOOKS B ON BR.BOOKID = B.BOOKID;

SELECT * FROM STUDENT_BORROWING_HISTORY WHERE STUDENTID = 1;

-- 4. BOOK_DETAILS: full info of each book (authors joined into one column)
CREATE OR REPLACE VIEW BOOK_DETAILS AS
SELECT B.BOOKID, B.TITLE, B.ISBN, B.CATEGORY, B.PUBLICATIONYEAR,
       GROUP_CONCAT(A.NAME SEPARATOR ', ') AS AUTHORS,
       P.NAME AS PUBLISHER, L.NAME AS LIBRARY
FROM BOOKS B
LEFT JOIN WRITTEN_BY WB ON B.BOOKID = WB.BOOKID
LEFT JOIN AUTHOR A ON WB.AUTHORID = A.AUTHORID
JOIN PUBLISHER P ON B.PUBLISHERID = P.PUBLISHERID
JOIN LIBRARY L ON B.LIBRARYID = L.LIBRARYID
GROUP BY B.BOOKID, B.TITLE, B.ISBN, B.CATEGORY, B.PUBLICATIONYEAR, P.NAME, L.NAME;

SELECT * FROM BOOK_DETAILS ORDER BY TITLE;

-- 5. OVERDUE_BOOKS: not returned and past due date
CREATE OR REPLACE VIEW OVERDUE_BOOKS AS
SELECT BR.BORROWID, S.STUDENTNAME, S.STUDENTEMAIL, B.TITLE,
       BR.DUE_DATE, DATEDIFF(CURDATE(), BR.DUE_DATE) AS DAYS_OVERDUE
FROM BORROW BR
JOIN STUDENT S ON BR.STUDENTID = S.STUDENTID
JOIN BOOKS B ON BR.BOOKID = B.BOOKID
WHERE BR.RETURNDATE IS NULL AND BR.DUE_DATE < CURDATE();

SELECT * FROM OVERDUE_BOOKS ORDER BY DAYS_OVERDUE DESC;

-- changing a view: CREATE OR REPLACE (MySQL also has ALTER VIEW)
ALTER VIEW CURRENT_BORROWINGS AS
SELECT BR.BORROWID, S.STUDENTID, S.STUDENTNAME, B.BOOKID, B.TITLE,
       L.NAME AS LIBRARY, BR.BORROWDATE, BR.DUE_DATE,
       DATEDIFF(CURDATE(), BR.DUE_DATE) AS DAYS_PAST_DUE
FROM BORROW BR
JOIN STUDENT S ON BR.STUDENTID = S.STUDENTID
JOIN BOOKS B ON BR.BOOKID = B.BOOKID
JOIN LIBRARY L ON B.LIBRARYID = L.LIBRARYID
WHERE BR.RETURNDATE IS NULL;

SELECT * FROM CURRENT_BORROWINGS;

