USE library_management_system;

-- ---------- DDL ----------

-- see table structure
DESCRIBE BOOKS;
DESCRIBE BORROW;
SHOW CREATE TABLE BORROW;

-- ALTER TABLE: add a temporary column
ALTER TABLE BOOKS ADD COLUMN NOTES VARCHAR(100) NULL;
DESCRIBE BOOKS;

-- ALTER TABLE: modify the column size
ALTER TABLE BOOKS MODIFY COLUMN NOTES VARCHAR(500) NULL;

-- ALTER TABLE: drop the temp column again
ALTER TABLE BOOKS DROP COLUMN NOTES;

-- ALTER TABLE: add a constraint (category can't be blank)
ALTER TABLE BOOKS ADD CONSTRAINT CK_BOOKS_CATEGORY CHECK (TRIM(CATEGORY) <> '');

-- list all constraints
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
WHERE TABLE_SCHEMA = 'library_management_system'
ORDER BY TABLE_NAME, CONSTRAINT_TYPE;

-- list foreign keys with their delete/update rules
SELECT TABLE_NAME, CONSTRAINT_NAME, REFERENCED_TABLE_NAME, UPDATE_RULE, DELETE_RULE
FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS
WHERE CONSTRAINT_SCHEMA = 'library_management_system';

