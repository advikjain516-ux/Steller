-- insert many rows at once
START TRANSACTION;
INSERT INTO STUDENT (USERID, STUDENTNAME, STUDENTEMAIL, STUDENTPHONENUMBER, BRANCH, SEMESTER) VALUES
('CS2026001', 'Riya Kapoor', 'riya.kapoor@college.edu', '9000000001', 'CSE', 1),
('IT2026001', 'Aman Verma',  'aman.verma@college.edu',  '9000000002', 'IT',  1);
SELECT * FROM STUDENT WHERE USERID IN ('CS2026001', 'IT2026001');
ROLLBACK;

-- insert a new book and link it to two authors
START TRANSACTION;
INSERT INTO BOOKS (TITLE, ISBN, CATEGORY, PUBLICATIONYEAR, PUBLISHERID, LIBRARYID)
VALUES ('Database System Concepts', '978-0073523323', 'Database', 2019, 1, 3);
SET @new_book = LAST_INSERT_ID();
INSERT INTO WRITTEN_BY (AUTHORID, BOOKID) VALUES (1, @new_book), (11, @new_book), (12, @new_book);
SELECT * FROM WRITTEN_BY WHERE BOOKID = @new_book;
ROLLBACK;

-- update one row
START TRANSACTION;
UPDATE STUDENT SET SEMESTER = 4 WHERE STUDENTID = 1;
SELECT STUDENTID, STUDENTNAME, SEMESTER FROM STUDENT WHERE STUDENTID = 1;
ROLLBACK;

-- update many rows
START TRANSACTION;
UPDATE STUDENT SET SEMESTER = SEMESTER + 1 WHERE BRANCH = 'ECE' AND SEMESTER < 8;
SELECT STUDENTID, STUDENTNAME, BRANCH, SEMESTER FROM STUDENT WHERE BRANCH = 'ECE';
ROLLBACK;

-- delete a row (add a publisher first, then delete it)
START TRANSACTION;
INSERT INTO PUBLISHER (NAME, NATIONALITY) VALUES ('Khanna Publishers', 'Indian');
SET @pub = LAST_INSERT_ID();
DELETE FROM PUBLISHER WHERE PUBLISHERID = @pub;
SELECT COUNT(*) AS should_be_zero FROM PUBLISHER WHERE PUBLISHERID = @pub;
ROLLBACK;

